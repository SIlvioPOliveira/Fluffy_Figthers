using System;

public enum GachaResult { Success, InvalidPool, InsufficientFunds, InventoryFull, InvalidTicket, Busy }

public sealed class GachaSystem
{
    private readonly GameCatalog catalog;
    private readonly CurrencyWallet wallet;
    private readonly PlayerInventory inventory;
    private bool busy;

    public GachaSystem(GameCatalog catalog, CurrencyWallet wallet, PlayerInventory inventory)
    {
        this.catalog = catalog != null ? catalog : throw new ArgumentNullException(nameof(catalog));
        this.wallet = wallet ?? throw new ArgumentNullException(nameof(wallet));
        this.inventory = inventory ?? throw new ArgumentNullException(nameof(inventory));
    }

    // Ticket is generated by the caller in [0, 10000), enabling deterministic tests.
    public GachaResult TryRoll(GachaPool pool, int ticket, out PetData reward)
    {
        reward = null;
        if (busy) return GachaResult.Busy;
        if (pool == null || !pool.IsValid(catalog)) return GachaResult.InvalidPool;
        if (ticket < 0 || ticket >= GachaPool.TotalWeight) return GachaResult.InvalidTicket;
        if (wallet.Balance < pool.Region.RollCost) return GachaResult.InsufficientFunds;
        PetData selected = pool.Select(ticket);
        if (selected == null) return GachaResult.InvalidPool;
        if (!inventory.CanAdd(selected.PetId, 1, 1)) return GachaResult.InventoryFull;

        // All validation happens first. These synchronous state changes have no callbacks between them.
        busy = true;
        try
        {
            wallet.TrySpendSilently(pool.Region.RollCost);
            inventory.TryAddSilently(selected.PetId, 1, 1);
            reward = selected;
            // A failing UI listener must not turn an already-completed purchase into a retry.
            try { wallet.NotifyChanged(); } catch (Exception e) { UnityEngine.Debug.LogException(e); }
            try { inventory.NotifyChanged(); } catch (Exception e) { UnityEngine.Debug.LogException(e); }
            return GachaResult.Success;
        }
        finally { busy = false; }
    }
}
